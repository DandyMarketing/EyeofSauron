/**
 * The dashboard as an Excel workbook, for the period the reader chose.
 *
 * Khai, 12 Oct 2026: "you should make the dashboard exportable" -- "make it
 * choosable": the period and the format are picked at export time. PDF is the
 * page itself through the browser's print; this is the Excel half, for
 * somebody who wants to work the numbers.
 *
 * THE SAME FIGURES AS THE PAGE, NOT A SECOND CALCULATION. It is built from the
 * payload `/api/dashboard` returns for that period, so the workbook cannot
 * disagree with the screen -- the Monday-board-versus-Revel problem is exactly
 * two calculations of one number, and this does not create a second one.
 * Definitions travel with the figures, because "net sales" means three things
 * in this business and a number without its definition gets compared with the
 * wrong one.
 */

import ExcelJS from 'exceljs';
import type { DashboardPayload } from './dashboard.js';

const MONEY = '"$"#,##0.00;[Red]-"$"#,##0.00;"-"';
const PCT1 = '0.0"%"';
const HEAD: Partial<ExcelJS.Style> = {
  font: { bold: true, color: { argb: 'FFFFFFFF' } },
  fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F2937' } },
};

function header(ws: ExcelJS.Worksheet, row: number, labels: string[]) {
  labels.forEach((l, i) => {
    const c = ws.getRow(row).getCell(i + 1);
    c.value = l; c.font = HEAD.font!; c.fill = HEAD.fill!;
    c.alignment = { wrapText: true, vertical: 'middle' };
  });
}

function title(ws: ExcelJS.Worksheet, text: string, sub: string) {
  ws.getCell('A1').value = text;
  ws.getCell('A1').font = { bold: true, size: 14 };
  ws.getCell('A2').value = sub;
  ws.getCell('A2').font = { italic: true, color: { argb: 'FF6B7280' } };
}

export async function buildDashboardWorkbook(p: DashboardPayload, generatedOn: string): Promise<ExcelJS.Workbook> {
  const w = p.window;
  const span = `${w.current.start} to ${w.current.end}`;
  const priorSpan = `${w.prior.start} to ${w.prior.end}`;
  const rows = p.group ? [p.group, ...p.venues] : p.venues;
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Sauron';

  // ---- Summary ----------------------------------------------------------------
  const s = wb.addWorksheet('Summary', { views: [{ state: 'frozen', ySplit: 6, xSplit: 1 }] });
  title(s, `Dashboard -- ${w.label}`, `${span}, against ${priorSpan} (the same days the period before). Generated by Sauron on ${generatedOn}.`);
  let r = 3;
  for (const warn of w.warnings ?? []) {
    s.getCell(`A${r}`).value = warn;
    s.getCell(`A${r}`).font = { color: { argb: 'FFB45309' } };
    r++;
  }
  r = Math.max(r, 5) + 1;
  const cols = [
    'Venue', 'Net sales', 'Net sales, period before', 'Change', 'Covers', 'Covers, period before', 'Change',
    'Spend per head', 'Spend per head, period before', 'Average check', 'Bills', 'Food & beverage sales',
    'Food sales', 'Beverage sales', 'Food share', 'Discounts', 'Discount rate', 'Service charge', 'Trading days', 'Closed days',
  ];
  header(s, r, cols);
  s.getRow(r).height = 32;
  const headerRow = r;
  r++;
  for (const v of rows) {
    const row = s.getRow(r);
    const pctOf = (m: { pct: number | null } | undefined) => (m && m.pct !== null ? m.pct : null);
    row.values = [
      v.venue, v.net_sales, v.prior.net_sales, pctOf(v.change.net_sales),
      v.covers, v.prior.covers, pctOf(v.change.covers),
      v.avg_spend_per_head, v.prior.avg_spend_per_head, v.avg_check, v.transactions,
      v.food_bev_sales, v.food_sales, v.beverage_sales, v.food_pct,
      v.total_discounts, v.discount_rate_pct, v.service_charge, v.trading_days, v.closed_days.join(', ') || null,
    ];
    [2, 3, 8, 9, 10, 12, 13, 14, 16, 18].forEach(c => { row.getCell(c).numFmt = MONEY; });
    [4, 7, 15, 17].forEach(c => { row.getCell(c).numFmt = PCT1; });
    if (p.group && v === p.group) row.font = { bold: true };
    r++;
  }
  s.columns.forEach((c, i) => { c.width = i === 0 ? 22 : i === 19 ? 24 : 14; });
  r++;
  const defs = [
    'Net sales: food and beverage less discounts, plus service charge, before GST -- Revel\'s "Total Sales".',
    'Food & beverage sales: before discounts and service charge -- the base every cost % divides by.',
    'Spend per head: food & beverage sales / covers. Average check: net sales / bills.',
    'Covers: completed SevenRooms covers, walk-ins included. A blank means no SevenRooms data, not zero guests.',
    'Change: % against the same days of the period before. Blank where there is nothing to compare with.',
  ];
  for (const d of defs) { s.getCell(`A${r}`).value = d; s.getCell(`A${r}`).font = { size: 9, color: { argb: 'FF6B7280' } }; r++; }
  s.autoFilter = { from: { row: headerRow, column: 1 }, to: { row: headerRow, column: cols.length } };

  // ---- Daily ------------------------------------------------------------------
  const d = wb.addWorksheet('Daily', { views: [{ state: 'frozen', ySplit: 4 }] });
  title(d, `Day by day -- ${w.label}`, `${span}. A closed day is blank, never zero.`);
  header(d, 4, ['Venue', 'Date', 'Net sales', 'Food & beverage sales', 'Food sales', 'Beverage sales', 'Covers']);
  let dr = 5;
  for (const v of p.venues) {
    for (const day of v.daily) {
      d.getRow(dr).values = [v.venue, day.date, day.net_sales, day.gross_sales, day.food_sales, day.beverage_sales, day.covers];
      [3, 4, 5, 6].forEach(c => { d.getRow(dr).getCell(c).numFmt = MONEY; });
      dr++;
    }
  }
  d.columns.forEach((c, i) => { c.width = i === 0 ? 22 : 15; });
  d.autoFilter = { from: { row: 4, column: 1 }, to: { row: 4, column: 7 } };

  // ---- Costs ------------------------------------------------------------------
  const c = wb.addWorksheet('Costs');
  title(c, 'Cost of sales', 'Flash COGS = purchases from supplier bills in the period, with no stock count. Monthly = the Xero P&L, which includes the month-end count.');
  let cr = 4;
  if (p.period_costs) {
    c.getCell(`A${cr}`).value = `Flash COGS, ${span}`; c.getCell(`A${cr}`).font = { bold: true }; cr++;
    header(c, cr, ['Venue', 'Food cost', 'Food sales', 'Food %', 'Food coverage %', 'Beverage cost', 'Beverage sales', 'Beverage %', 'Beverage coverage %', 'Status']);
    cr++;
    for (const v of rows) {
      const k = p.period_costs[v.slug];
      if (!k) continue;
      const row = c.getRow(cr);
      row.values = [
        v.venue, k.food.cogs, k.food.sales, k.food.usable ? k.food.pct : null, k.food.coverage_pct,
        k.beverage.cogs, k.beverage.sales, k.beverage.usable ? k.beverage.pct : null, k.beverage.coverage_pct,
        k.settlement?.status ?? null,
      ];
      [2, 3, 6, 7].forEach(x => { row.getCell(x).numFmt = MONEY; });
      [4, 5, 8, 9].forEach(x => { row.getCell(x).numFmt = PCT1; });
      cr++;
    }
    c.getCell(`A${cr}`).value = 'A % is blank where bills explain too little of the ledger for it to mean anything. Over 100% coverage usually means stock built up.';
    c.getCell(`A${cr}`).font = { size: 9, color: { argb: 'FF6B7280' } };
    cr += 2;
  }
  if (p.costs) {
    const first = Object.values(p.costs)[0];
    c.getCell(`A${cr}`).value = `Monthly cost of sales, ${first?.month.label ?? ''} (Xero P&L)`;
    c.getCell(`A${cr}`).font = { bold: true }; cr++;
    header(c, cr, ['Venue', 'Food cost', 'Food sales', 'Food %', 'Beverage cost', 'Beverage sales', 'Beverage %', 'Combined %', 'Books open until']);
    cr++;
    for (const v of rows) {
      const k = p.costs[v.slug];
      if (!k || !k.available) continue;
      const rt = k.ratios;
      const row = c.getRow(cr);
      row.values = [v.venue, rt.food.cogs, rt.food.sales, rt.food.pct, rt.beverage.cogs, rt.beverage.sales, rt.beverage.pct, rt.combined.pct, k.open_until ?? 'closed'];
      [2, 3, 5, 6].forEach(x => { row.getCell(x).numFmt = MONEY; });
      [4, 7, 8].forEach(x => { row.getCell(x).numFmt = PCT1; });
      cr++;
    }
  }
  if (!p.period_costs && !p.costs) c.getCell('A4').value = 'No cost figures were available for this period.';
  c.columns.forEach((col, i) => { col.width = i === 0 ? 22 : 14; });

  return wb;
}
