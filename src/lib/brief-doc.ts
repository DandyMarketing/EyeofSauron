/**
 * The event brief as a Word document, and as the text of a Monday update.
 *
 * Khai, 12 Oct 2026: the brief goes into the event's "Concept & Mechanics"
 * item and the P&L into "Financial Forecast", each by choice; and each can be
 * downloaded on its own, the brief as Word and as PDF. The activation boards
 * have no Files column, so a file goes on as an attachment to an UPDATE on
 * the item -- and the update's own text is the brief, so it can be read inside
 * Monday without opening anything.
 *
 * ONE PARSE, TWO RENDERINGS. The brief is the planner's markdown. It is parsed
 * once into blocks here, and both outputs are drawn from those blocks, so the
 * Word file and the Monday text cannot disagree about what the brief says.
 * The PDF is the browser printing the page's own rendering of the same text.
 *
 * Deliberately small: headings, paragraphs, lists, tables, bold, italic and
 * code -- what the planner writes. Anything else arrives as plain text, which
 * is the safe direction to be wrong in.
 */

import {
  Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell,
  WidthType, AlignmentType,
} from 'docx';

export type Block =
  | { type: 'heading'; level: number; text: string }
  | { type: 'para'; text: string }
  | { type: 'list'; ordered: boolean; items: string[] }
  | { type: 'table'; rows: string[][] };

const isTableLine = (l: string) => /^\s*\|.*\|\s*$/.test(l);
const isSeparator = (l: string) => /^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$/.test(l);
const cells = (l: string) => l.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map(c => c.trim());

export function parseBrief(md: string): Block[] {
  const lines = String(md ?? '').replace(/\r\n?/g, '\n').split('\n');
  const out: Block[] = [];
  let para: string[] = [];
  const flush = () => { if (para.length) { out.push({ type: 'para', text: para.join(' ').trim() }); para = []; } };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!line.trim() || /^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(line)) { flush(); continue; }
    const h = /^\s*(#{1,6})\s+(.*)$/.exec(line);
    if (h) { flush(); out.push({ type: 'heading', level: h[1].length, text: h[2].replace(/\s*#+\s*$/, '').trim() }); continue; }
    if (isTableLine(line)) {
      flush();
      const rows: string[][] = [];
      for (; i < lines.length && isTableLine(lines[i]); i++) {
        if (!isSeparator(lines[i])) rows.push(cells(lines[i]));
      }
      i--;
      out.push({ type: 'table', rows });
      continue;
    }
    const ul = /^\s*[-*•]\s+(.*)$/.exec(line);
    const ol = /^\s*\d+[.)]\s+(.*)$/.exec(line);
    if (ul || ol) {
      flush();
      const ordered = !!ol;
      const items: string[] = [];
      for (; i < lines.length; i++) {
        const m = ordered ? /^\s*\d+[.)]\s+(.*)$/.exec(lines[i]) : /^\s*[-*•]\s+(.*)$/.exec(lines[i]);
        if (!m) break;
        items.push(m[1].trim());
      }
      i--;
      out.push({ type: 'list', ordered, items });
      continue;
    }
    para.push(line.trim());
  }
  flush();
  return out;
}

/** Bold, italic and code within a line, as runs. Unmatched markers stay as text. */
export function inlineRuns(text: string): Array<{ text: string; bold?: boolean; italics?: boolean; code?: boolean }> {
  const parts = text.split(/(\*\*[^*]+\*\*|__[^_]+__|\*[^*\s][^*]*\*|`[^`]+`)/g).filter(p => p !== '');
  return parts.map(p => {
    if (/^(\*\*|__).+\1$/.test(p)) return { text: p.slice(2, -2), bold: true };
    if (/^\*.+\*$/.test(p)) return { text: p.slice(1, -1), italics: true };
    if (/^`.+`$/.test(p)) return { text: p.slice(1, -1), code: true };
    return { text: p };
  });
}

const runs = (text: string, extra: { bold?: boolean } = {}) =>
  inlineRuns(text).map(r => new TextRun({ text: r.text, bold: r.bold || extra.bold, italics: r.italics, font: r.code ? 'Consolas' : undefined }));

const HEADINGS = [HeadingLevel.HEADING_1, HeadingLevel.HEADING_2, HeadingLevel.HEADING_3, HeadingLevel.HEADING_4, HeadingLevel.HEADING_5, HeadingLevel.HEADING_6];

/** The brief as a .docx, titled, with the date it was generated. */
export async function briefDocx(md: string, meta: { title: string; subtitle?: string; generatedOn: string }): Promise<Buffer> {
  const children: Array<Paragraph | Table> = [
    new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun(meta.title)] }),
    new Paragraph({ children: [new TextRun({ text: `${meta.subtitle ? meta.subtitle + ' · ' : ''}Event brief, generated by Sauron on ${meta.generatedOn}`, italics: true, color: '6B7280' })] }),
  ];
  for (const b of parseBrief(md)) {
    if (b.type === 'heading') children.push(new Paragraph({ heading: HEADINGS[Math.min(b.level, 6) - 1], children: runs(b.text) }));
    else if (b.type === 'para') children.push(new Paragraph({ children: runs(b.text), spacing: { after: 120 } }));
    else if (b.type === 'list') {
      b.items.forEach((it, n) => children.push(b.ordered
        ? new Paragraph({ children: [new TextRun(`${n + 1}. `), ...runs(it)], indent: { left: 360 } })
        : new Paragraph({ children: runs(it), bullet: { level: 0 } })));
    } else if (b.type === 'table' && b.rows.length) {
      const width = Math.max(...b.rows.map(r => r.length));
      children.push(new Table({
        width: { size: 100, type: WidthType.PERCENTAGE },
        rows: b.rows.map((r, ri) => new TableRow({
          tableHeader: ri === 0,
          children: Array.from({ length: width }, (_, ci) => new TableCell({
            children: [new Paragraph({ alignment: AlignmentType.LEFT, children: runs(r[ci] ?? '', { bold: ri === 0 }) })],
          })),
        })),
      }));
      children.push(new Paragraph({ children: [] }));
    }
  }
  const doc = new Document({ creator: 'Sauron', title: meta.title, sections: [{ children }] });
  return Packer.toBuffer(doc);
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const inlineHtml = (text: string) => inlineRuns(text).map(r => {
  const t = esc(r.text);
  return r.bold ? `<strong>${t}</strong>` : r.italics ? `<em>${t}</em>` : r.code ? `<code>${t}</code>` : t;
}).join('');

/**
 * The brief as a Monday update body. Monday's update editor takes simple HTML;
 * tables are written as lines, header first, because a table that does not
 * render is worse than one that reads as a list. Capped, with the attached
 * file named as the full version, since an update has a size limit.
 */
export function briefMondayHtml(md: string, title: string, limit = 20000): string {
  const parts: string[] = [`<p><strong>${esc(title)} -- event brief from Sauron</strong></p>`];
  for (const b of parseBrief(md)) {
    if (b.type === 'heading') parts.push(`<p><strong>${inlineHtml(b.text)}</strong></p>`);
    else if (b.type === 'para') parts.push(`<p>${inlineHtml(b.text)}</p>`);
    else if (b.type === 'list') parts.push(`<${b.ordered ? 'ol' : 'ul'}>${b.items.map(i => `<li>${inlineHtml(i)}</li>`).join('')}</${b.ordered ? 'ol' : 'ul'}>`);
    else if (b.type === 'table' && b.rows.length) {
      const [head, ...rest] = b.rows;
      parts.push(`<p><em>${head.map(inlineHtml).join(' · ')}</em></p>`);
      parts.push(`<ul>${rest.map(r => `<li>${r.map(inlineHtml).join(' · ')}</li>`).join('')}</ul>`);
    }
  }
  let html = parts.join('');
  if (html.length > limit) html = html.slice(0, limit).replace(/<[^>]*$/, '') + '<p><em>... cut for length. The full brief is the attached Word file.</em></p>';
  return html;
}
