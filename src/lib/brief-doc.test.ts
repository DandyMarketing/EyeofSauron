/**
 * The brief as Word and as a Monday update: one parse, two renderings, so the
 * two cannot disagree about what the brief says.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import JSZip from 'jszip';
import { parseBrief, inlineRuns, briefMondayHtml, briefDocx } from './brief-doc.js';

const brief = `# NYE at Neon Pigeon

A **two-floor** night, *ticketed*.

## What to push hardest
| Draw | Push | Why |
|---|---|---|
| Star DJ | lead | Nobody else has him |
| Free flow | support | Expected <at> this price |

- Launch on 7 Dec
- Phone last year's tables

1. Strategy
2. Menus
---
Plain closing line.`;

test('the planner\'s markdown is read into headings, paragraphs, tables and lists', () => {
  const b = parseBrief(brief);
  assert.deepEqual(b.map(x => x.type), ['heading', 'para', 'heading', 'table', 'list', 'list', 'para']);
  const table = b[3] as any;
  assert.deepEqual(table.rows[0], ['Draw', 'Push', 'Why']);
  assert.equal(table.rows.length, 3, 'the --- separator row is not a row');
  assert.equal((b[5] as any).ordered, true);
});

test('bold, italic and code become runs; a stray asterisk stays text', () => {
  assert.deepEqual(inlineRuns('a **b** *c* `d`'), [
    { text: 'a ' }, { text: 'b', bold: true }, { text: ' ' }, { text: 'c', italics: true }, { text: ' ' }, { text: 'd', code: true },
  ]);
  assert.deepEqual(inlineRuns('5 * 3'), [{ text: '5 * 3' }]);
});

test('the Monday text is escaped, and a table reads as lines', () => {
  const html = briefMondayHtml(brief, 'NYE');
  assert.match(html, /<strong>two-floor<\/strong>/);
  assert.match(html, /<li>Free flow · support · Expected &lt;at&gt; this price<\/li>/);
  assert.doesNotMatch(html, /<at>/);
  assert.match(html, /<ol><li>Strategy<\/li><li>Menus<\/li><\/ol>/);
});

test('an over-long brief is cut, and says the full one is attached', () => {
  const html = briefMondayHtml('para '.repeat(10000), 'NYE', 500);
  assert.ok(html.length < 700);
  assert.match(html, /full brief is the attached Word file/);
});

test('the Word file is a real document carrying the brief\'s text', async () => {
  const buf = await briefDocx(brief, { title: 'NYE at Neon Pigeon', subtitle: '2026-12-31', generatedOn: '2026-10-12' });
  const zip = await JSZip.loadAsync(buf);
  const xml = await zip.file('word/document.xml')!.async('string');
  for (const s of ['NYE at Neon Pigeon', 'Star DJ', 'Nobody else has him', 'Phone last year', 'generated by Sauron on 2026-10-12']) {
    assert.ok(xml.includes(s), `missing: ${s}`);
  }
});
